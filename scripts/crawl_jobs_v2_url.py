"""Independent, offline Python validation of canonical URL V1 identities.

Authority: Go 1.25.13, x/net v0.58.0, x/text v0.41.0, Unicode 15.0.0.
Only immutable property bytes are shared with Lua. No Lua, Go, subprocess,
network, Python IDNA codec, or host unicodedata implementation is executed here.
The checked-in data is loaded from ONE fixed path relative to this helper, never
from a fixture, current directory, environment variable, or search path.

Identity is NOT crawl admission. validate_identity permits IP/local/non-default
port identities; derive_origin additionally rejects IPs. Policy, transcript and
source/discovery binding callers must explicitly derive_origin. Structural
output/chunk codecs and URL-ID hashes use validate_identity. Neither operation
authorizes a network request or replaces static/dynamic crawl policy.

The NFC and IDNA algorithms preserve the pinned Go implementation details, not
an idealized replacement standard: byte-indexed hyphens, no ContextO, conditional
per-label bidi, ContextJ zero-default transitions, stream-safe normalization,
and the uint16-truncated composition keys. Adapted from the Go Authors' 2011
and 2016 sources; BSD-3-Clause/PATENTS and Unicode notices are retained beside
the data in services/spider/internal/database/crawljobsv2/lua_src/licenses/.
"""

